/**
 * Post-Session Error Consolidator & Summary Generator
 * 
 * Takes all errors logged during a voice session, deduplicates and ranks them
 * into 3 tiers (Fix First, Sounds Off, Small Things), generates the learner-friendly
 * spoken summary, and updates the learner's cumulative profile.
 */

const prisma = require('../lib/prisma')

// Severity weights for ranking
const SEVERITY_WEIGHTS = {
  blocks_understanding: 3,
  sounds_non_native: 2,
  minor: 1,
}

// 10-type error classification tier mapping
const TYPE_TIER_DEFAULTS = {
  sound_swap: 'fix_first',
  word_stress: 'sounds_off',
  grammar: 'fix_first',
  word_choice: 'sounds_off',
  sentence_shape: 'fix_first',
  hesitation: 'sounds_off',
  speed: 'sounds_off',
  too_short: 'fix_first',
  indian_english: 'small_things',
  unclear: 'fix_first',
}

/**
 * Consolidate and rank errors for a completed voice session.
 * 
 * @param {number} sessionId 
 * @returns {Promise<object>} Consolidated session result
 */
async function consolidateSessionErrors(sessionId) {
  const sid = parseInt(sessionId)
  const session = await prisma.voice_sessions.findUnique({
    where: { id: sid },
    include: {
      errors: true,
      turns: { orderBy: { sequence: 'asc' } },
      user: true,
    },
  })

  if (!session) {
    throw new Error(`Voice session ${sid} not found`)
  }

  const rawErrors = session.errors || []

  // 1. Deduplicate & group similar errors
  const errorMap = new Map()

  for (const err of rawErrors) {
    const key = `${err.error_type}:${(err.said || '').toLowerCase().trim()}->${(err.correct || '').toLowerCase().trim()}`
    if (errorMap.has(key)) {
      const existing = errorMap.get(key)
      existing.count = (existing.count || 1) + 1
      if (err.corrected_aloud) existing.corrected_aloud = true
      if (err.learner_repeated_correctly) existing.learner_repeated_correctly = true
    } else {
      errorMap.set(key, {
        id: err.id,
        error_type: err.error_type,
        said: err.said,
        correct: err.correct,
        target_word: err.target_word,
        detail: err.detail,
        severity: err.severity || 'sounds_non_native',
        confidence: err.confidence || 'medium',
        corrected_aloud: err.corrected_aloud || false,
        learner_repeated_correctly: err.learner_repeated_correctly,
        count: 1,
      })
    }
  }

  const uniqueErrors = Array.from(errorMap.values())

  // 2. Assign tiers and calculate priority score
  // Priority = count * severity_weight * (confidence === 'high' ? 1.5 : 1.0)
  const rankedErrors = uniqueErrors.map((err) => {
    const sevWeight = SEVERITY_WEIGHTS[err.severity] || 1
    const confWeight = err.confidence === 'high' ? 1.5 : 1.0
    const priority = err.count * sevWeight * confWeight

    // Default tier from type, or override by severity
    let tier = TYPE_TIER_DEFAULTS[err.error_type] || 'sounds_off'
    if (err.severity === 'blocks_understanding') {
      tier = 'fix_first'
    } else if (err.severity === 'minor') {
      tier = 'small_things'
    }

    return {
      ...err,
      priority,
      tier,
    }
  })

  // Sort descending by priority
  rankedErrors.sort((a, b) => b.priority - a.priority)

  // 3. Separate into the 3 tiers
  // "Fix these first": max 3 items
  const fixFirst = rankedErrors.filter((e) => e.tier === 'fix_first').slice(0, 3)
  const fixFirstIds = new Set(fixFirst.map((e) => e.id))

  const soundsOff = rankedErrors.filter((e) => (e.tier === 'sounds_off' || (e.tier === 'fix_first' && !fixFirstIds.has(e.id))))
  const smallThings = rankedErrors.filter((e) => e.tier === 'small_things')

  // Update tiers in DB
  for (const err of fixFirst) {
    await prisma.session_errors.update({ where: { id: err.id }, data: { tier: 'fix_first' } }).catch(() => {})
  }
  for (const err of soundsOff) {
    await prisma.session_errors.update({ where: { id: err.id }, data: { tier: 'sounds_off' } }).catch(() => {})
  }
  for (const err of smallThings) {
    await prisma.session_errors.update({ where: { id: err.id }, data: { tier: 'small_things' } }).catch(() => {})
  }

  // 4. Generate post-session spoken summary if not already generated by session_complete
  let summary = session.summary_text
  let learnerDidWell = session.learner_did_well
  let oneThingToFix = session.one_thing_to_fix

  if (!summary) {
    const minutesSpoken = Math.max(1, Math.round((session.duration_seconds || 0) / 60))
    if (fixFirst.length > 0) {
      const topMistake = fixFirst[0]
      learnerDidWell = 'You answered every question confidently and kept the conversation going.'
      oneThingToFix = `You said "${topMistake.said || 'this'}" — in English we say "${topMistake.correct || 'the correct form'}".`
      summary = `You spoke for ${minutesSpoken} minutes today. That was great practice! You answered every question confidently. One thing to work on: you said "${topMistake.said || ''}" — remember to say "${topMistake.correct || ''}". Keep practising!`
    } else {
      learnerDidWell = 'Your pronunciation was clear and your sentences were easy to understand.'
      oneThingToFix = 'Keep practising longer sentences to build more fluency.'
      summary = `You spoke for ${minutesSpoken} minutes today. Great job! Your pronunciation was clear and you communicated your ideas smoothly. Next time, try building longer sentences.`
    }

    await prisma.voice_sessions.update({
      where: { id: sid },
      data: {
        summary_text: summary,
        learner_did_well: learnerDidWell,
        one_thing_to_fix: oneThingToFix,
      },
    }).catch((err) => console.error('[ErrorConsolidator] Failed to save summary:', err))
  }

  // 5. Update learner's cumulative profile
  if (session.user_id) {
    try {
      const sessionMinutes = Math.round((session.duration_seconds || 0) / 60)
      const topErrorPatterns = fixFirst.map((e) => `${e.said} → ${e.correct}`)

      await prisma.learner_profiles.upsert({
        where: { user_id: session.user_id },
        update: {
          total_sessions: { increment: 1 },
          total_minutes: { increment: sessionMinutes },
          current_track: session.track_key,
          current_chapter: session.chapter_key,
          open_errors: topErrorPatterns,
          updated_at: new Date(),
        },
        create: {
          user_id: session.user_id,
          total_sessions: 1,
          total_minutes: sessionMinutes,
          current_track: session.track_key,
          current_chapter: session.chapter_key,
          open_errors: topErrorPatterns,
          english_level: 'Beginner',
        },
      })
    } catch (err) {
      console.error('[ErrorConsolidator] Failed to update learner profile:', err)
    }
  }

  return {
    sessionId: sid,
    durationSeconds: session.duration_seconds || 0,
    questionsAsked: session.questions_asked || 0,
    wordsSpoken: session.words_spoken || 0,
    summary,
    learnerDidWell,
    oneThingToFix,
    tiers: {
      fixFirst,
      soundsOff,
      smallThings,
      totalCount: uniqueErrors.length,
    },
  }
}

module.exports = {
  consolidateSessionErrors,
}
